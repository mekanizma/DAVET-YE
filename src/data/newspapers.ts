import type { Locale } from "@/i18n/locale";

export interface Newspaper {
  slug: string;
  title: string;
  eyebrow: string;
  description: string;
  price: number;
  compareAt: number;
  /** Yerel kapak görseli; yoksa CSS ile üretilen tipografik kapak kullanılır. */
  cover?: string;
  /** CSS kapak için manşet ve alt başlık */
  headline: string;
  tagline: string;
  paper: string;
  ink: string;
  accent: string;
}

export const NEWSPAPER_STYLES = [
  { id: "original", label: "Orijinal", filter: "none" },
  { id: "sepia", label: "Eski kâğıt", filter: "sepia(0.55) contrast(1.02)" },
  { id: "mono", label: "Siyah beyaz", filter: "grayscale(1) contrast(1.05)" },
] as const;

export type NewspaperStyleId = (typeof NEWSPAPER_STYLES)[number]["id"];

const NEWSPAPER_STYLE_EN: Record<NewspaperStyleId, string> = {
  original: "Original",
  sepia: "Aged paper",
  mono: "Black and white",
};

/** Turkish labels stay on NEWSPAPER_STYLES. English labels when locale is en. */
export function newspaperStyles(locale: Locale = "tr") {
  if (locale !== "en") return NEWSPAPER_STYLES;
  return NEWSPAPER_STYLES.map((style) => ({
    ...style,
    label: NEWSPAPER_STYLE_EN[style.id],
  }));
}

