function applyCase(source: string, english: string) {
  if (source.length > 2 && source === source.toLocaleUpperCase("tr")) return english.toLocaleUpperCase("en-GB");
  if (source[0] === source[0]?.toLocaleLowerCase("tr")) {
    return english.charAt(0).toLocaleLowerCase("en-GB") + english.slice(1);
  }
  return english;
}

/** Editor labels baked into the newspaper templates. Visible newspaper copy stays as designed. */
export function editorLabel(raw: string, locale: Locale): string {
  if (locale !== "en") return raw;
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  const key = trimmed.toLocaleLowerCase("tr");
  if (EXACT[key]) return EXACT[key];

  const timed = key
    .replace(/^saat\s+(\d{1,2}[.:]\d{2})$/i, (_, clock: string) => `Time ${clock}`)
    .replace(/^program\s+(\d{1,2}[.:]\d{2})$/i, (_, clock: string) => `Programme ${clock}`)
    .replace(/^fotoğraf\s+(\d+)$/i, (_, n: string) => `Photo ${n}`)
    .replace(/^manşet\s+(\d+)$/i, (_, n: string) => `Headline ${n}`)
    .replace(/^alıntı\s+(\d+)$/i, (_, n: string) => `Quote ${n}`)
    .replace(/^fihrist\s+(\d+)$/i, (_, n: string) => `Contents ${n}`)
    .replace(/^çizelge\s+(\d+)\s+başlık$/i, (_, n: string) => `Chart ${n} heading`);
  if (timed !== key) return timed.charAt(0).toLocaleUpperCase("en-GB") + timed.slice(1);

  if (!/[çğıöşüÇĞİÖŞÜ]/.test(trimmed) && !EXACT[key]) {
    const onlyKnown = key.split(/\s+/).every((part) => TOKEN[part] || /^\d+(?:[.:]\d+)?$/.test(part));
    if (!onlyKnown) return raw;
  }

  const parts = trimmed.split(/(\s+)/);
  const next = parts.map((part) => {
    if (!part.trim()) return part;
    const match = part.match(/^([^\p{L}\p{N}]*)([\p{L}\p{N}]+)([^\p{L}\p{N}]*)$/u);
    if (!match) return part;
    const token = match[2].toLocaleLowerCase("tr");
    const english = TOKEN[token];
    if (english === undefined) return part;
    if (!english) return match[1] + match[3];
    return match[1] + applyCase(match[2], english) + match[3];
  });
  const joined = next.join("").replace(/\s+/g, " ").trim();
  return joined.charAt(0).toLocaleUpperCase("en-GB") + joined.slice(1);
}
